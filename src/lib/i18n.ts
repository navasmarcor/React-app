export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}) {
  const raw = STRINGS[lang][key] ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function useT() {
  const { state } = useStore();
  const lang = state.lang;
  const t = (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
  const ev = (name: string) => EVENT_NAMES[lang]?.[name] ?? name;
  return { t, ev, lang };
}
